CREATE TABLE CLIENT AS SELECT * FROM company_2025.CLIENT;
CREATE TABLE `ORDER` AS SELECT * FROM company_2025.`ORDER`;
CREATE TABLE EMPLOYE AS SELECT * FROM company_2025.EMPLOYEE;

SELECT * FROM `ORDER`;

SELECT * FROM `ORDER` WHERE ORDER_STATUS = 5;

SELECT ORDER_ID, ORDER_STATUS FROM `ORDER` WHERE CLIENT_ID IN (1, 3, 5);

SELECT * FROM EMPLOYE WHERE FIRST_NAME = "Agnieszka" AND pensja = 3900;

SELECT * FROM EMPLOYE WHERE pensja between '5000' AND '7000';

SELECT * FROM CLIENT WHERE SHORT_NAME LIKE "%eco%" AND IS_COMPANY = 1;

SELECT * FROM `ORDER`;
SELECT * FROM `ORDER` WHERE ORDER_DATE LIKE "%-06-%" OR ORDER_DATE LIKE "%-07-%";

SELECT * FROM CLIENT WHERE TAX_IDENTIFIER IS NOT NULL ORDER BY SHORT_NAME ASC;

SELECT * FROM EMPLOYE ORDER BY BIRTH_DATE LIMIT 5;

SELECT DISTINCT FIRST_NAME FROM EMPLOYE; 

SELECT CONCAT(FIRST_NAME, " - ", LAST_NAME) AS pracownik FROM EMPLOYE WHERE LAST_NAME LIKE "Ko%";

SELECT LAST_NAME, pensja FROM EMPLOYE WHERE DATE_OF_EMPLOYMENT between "2010-01-01" AND "2014-12-31";

SELECT pensja, (pensja*0.75) as pensja_netto, (pensja*0.25) as kwota_podatku FROM EMPLOYE;

SELECT * FROM CLIENT WHERE TAX_IDENTIFIER IS NULL;

SELECT SHORT_NAME FROM CLIENT WHERE FULL_NAME LIKE "K%" OR FULL_NAME LIKE "%ski" ORDER BY SHORT_NAME DESC;